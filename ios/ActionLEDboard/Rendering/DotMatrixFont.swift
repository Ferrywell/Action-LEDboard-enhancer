    static func rows(for character: Character) -> [String] {
        let s = String(character).uppercased()
        guard let first = s.first else { return patterns[" "]! }
        return patterns[first] ?? patterns[" "]!
    }

    /// Pixel width at scale 1 (matches Python `get_text_width` for known glyphs; unknown glyphs use space width).
    static func textWidth(_ text: String) -> Int {
        var width = 0
        for _ in text.uppercased() {
            width += charWidth + charSpacing
        }
        return max(0, width - charSpacing)
    }
}
