/// 5×7 dot-matrix glyphs aligned with `reference/panel-hopper-github/src/panel_hopper/graphics.py` (`DOT_MATRIX_FONT`).
/// Each `#` maps to one LED; spaces are off — matches physical pixel placement on BK-Light 32×32 panels.
